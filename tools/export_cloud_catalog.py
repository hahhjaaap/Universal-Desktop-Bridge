from __future__ import annotations

import json
from pathlib import Path

from udb._version import VERSION
from udb.companion.runtime import TOOLS as COMPANION_TOOLS
from udb.registry import catalog
from udb.tool_policy import DEFAULT_READ_TOOLS, SCOPES, TOOL_POLICY

ROOT = Path(__file__).resolve().parents[1]
CLOUDFLARE = ROOT / "cloudflare"
GENERATED = CLOUDFLARE / "src" / "generated"
COMPANION_NAMES = {tool["name"] for tool in COMPANION_TOOLS}
BACKEND_ALIASES = {"file_transfer": "file_copy"}


def local_gate(name: str, backend: str, scope: str) -> str:
    if backend == "companion":
        return "attended_computer_access_and_project_root"
    return {
        "udb:read": "registered_project_read_permissions",
        "udb:observe": "local_observation_permissions",
        "udb:write": "registered_project_write_permissions_and_review",
        "udb:execute": "terminal_enablement_and_owner_policy",
        "udb:sandbox": "sandbox_owner_grant_or_local_approval",
        "udb:host": "separate_owned_host_session_policy",
        "udb:computer": "attended_current_user_computer_grant",
        "udb:download": "local_download_review_and_https_allowlist",
        "udb:jobs": "owner_job_permissions",
    }[scope]


def main() -> None:
    result = catalog()
    public_tools = result["tools"]
    names = [tool["name"] for tool in public_tools]
    if len(names) != 59 or len(set(names)) != 59:
        raise SystemExit("Expected exactly 59 unique public UDB tools")

    tools = []
    for source in public_tools:
        name = source["name"]
        policy = dict(TOOL_POLICY[name])
        scopes = list(policy["scopes"])
        if len(scopes) != 1 or scopes[0] not in SCOPES:
            raise SystemExit(f"Invalid scope for {name}")
        route_name = BACKEND_ALIASES.get(name, name)
        backend = "companion" if route_name in COMPANION_NAMES else "core"
        annotations = dict(source.get("annotations") or {})
        annotations.setdefault("readOnlyHint", policy["readOnly"])
        annotations.setdefault("destructiveHint", policy["destructive"])
        annotations.setdefault("idempotentHint", policy["idempotent"])
        annotations.setdefault("openWorldHint", policy["openWorld"])
        for field, key in (
            ("readOnlyHint", "readOnly"),
            ("destructiveHint", "destructive"),
            ("openWorldHint", "openWorld"),
        ):
            if annotations[field] != policy[key]:
                raise SystemExit(
                    f"Annotation mismatch for {name}: {field} "
                    f"{annotations[field]!r} != {policy[key]!r}"
                )
        tools.append(
            {
                "name": name,
                "description": source["description"],
                "inputSchema": source["inputSchema"],
                "annotations": annotations,
                "securitySchemes": [{"type": "oauth2", "scopes": scopes}],
                "policy": {
                    "category": policy["category"],
                    "scopes": scopes,
                    "defaultEnabled": policy["defaultEnabled"],
                    "risk": policy["risk"],
                    "parallelSafe": policy["parallelSafe"],
                    "requiresLocalApproval": policy["requiresLocalApproval"],
                    "localGate": local_gate(name, backend, scopes[0]),
                    "backend": backend,
                },
            }
        )

    manifest = {
        "schemaVersion": 1,
        "udbVersion": VERSION,
        "toolCount": len(tools),
        "coreBackendCount": result["core_count"],
        "companionBackendCount": result["companion_count"],
        "uniqueBackendCount": result["backend_count"],
        "defaultTools": sorted(DEFAULT_READ_TOOLS),
        "scopes": dict(SCOPES),
        "tools": tools,
    }
    CLOUDFLARE.mkdir(parents=True, exist_ok=True)
    GENERATED.mkdir(parents=True, exist_ok=True)
    json_text = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
    (CLOUDFLARE / "tool-catalog.json").write_text(json_text, encoding="utf-8")
    js = (
        "// Generated by tools/export_cloud_catalog.py; do not edit manually.\n"
        "export const TOOL_CATALOG = Object.freeze("
        + json.dumps(tools, ensure_ascii=False, separators=(",", ":"))
        + ");\n"
        "export const TOOL_BY_NAME = new Map(TOOL_CATALOG.map((tool) => [tool.name, tool]));\n"
        "export const DEFAULT_TOOL_NAMES = Object.freeze("
        + json.dumps(sorted(DEFAULT_READ_TOOLS))
        + ");\n"
    )
    (GENERATED / "tool-catalog.js").write_text(js, encoding="utf-8")

    rows = [
        "# UDB public tool permissions",
        "",
        f"- UDB version: {VERSION}",
        f"- Public tools: **{len(tools)}**",
        f"- Core backend tools before consolidation: {result['core_count']}",
        f"- Companion backend tools before consolidation: {result['companion_count']}",
        f"- Unique backend tools before consolidation: {result['backend_count']}",
        "",
        "New connections receive only the six explicitly reviewed read tools. All other tools require a separate scope and explicit device/user grant. Windows-side permissions remain authoritative.",
        "",
        "| Tool | Scope | Risk | Backend | Local gate |",
        "|---|---|---|---|---|",
    ]
    for tool in tools:
        p = tool["policy"]
        rows.append(
            f"| {tool['name']} | {p['scopes'][0]} | {p['risk']} | "
            f"{p['backend']} | {p['localGate']} |"
        )
    (ROOT / "docs" / "tool-permissions.md").write_text(
        "\n".join(rows) + "\n", encoding="utf-8"
    )
    print(
        json.dumps(
            {
                "tools": len(tools),
                "defaultTools": sorted(DEFAULT_READ_TOOLS),
                "scopes": {
                    scope: sum(scope in t["policy"]["scopes"] for t in tools)
                    for scope in SCOPES
                },
                "backends": {
                    "core": sum(t["policy"]["backend"] == "core" for t in tools),
                    "companion": sum(
                        t["policy"]["backend"] == "companion" for t in tools
                    ),
                },
                "files": [
                    str(CLOUDFLARE / "tool-catalog.json"),
                    str(GENERATED / "tool-catalog.js"),
                    str(ROOT / "docs" / "tool-permissions.md"),
                ],
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
